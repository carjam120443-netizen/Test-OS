static int glyph_index(char c) {
    if (c >= 'A' && c <= 'Z') return c - 'A';
    if (c >= '0' && c <= '9') return 26 + c - '0';
    return -1;
}

static void text(uint32_t x, uint32_t y, const char *s, uint32_t color, uint32_t scale) {
    while (*s) {
        int index = glyph_index(*s++);
        if (index < 0) { x += 6 * scale; continue; }
        for (uint32_t row = 0; row < 7; ++row)
            for (uint32_t col = 0; col < 5; ++col)
                if (glyphs[index][row] & (1u << (4 - col)))
                    rect(x + col * scale, y + row * scale, scale, scale, color);
        x += 6 * scale;
    }
}

void desktop_redraw(void) {
    if (!graphics_ready()) return;
    const struct framebuffer *fb = graphics_framebuffer();
    const uint32_t panel_h = fb->height >= 600 ? 52 : 40;

    graphics_clear(BG);

    /* Simple desktop accents. */
    rect(0, 0, fb->width, 5, ACCENT);
    rect(0, fb->height - panel_h, fb->width, panel_h, PANEL);
    rect(0, fb->height - panel_h, fb->width, 1, PANEL_EDGE);

    /* Application launcher button. */
    rect(14, fb->height - panel_h + 10, 30, panel_h - 20, ACCENT);
    text(21, fb->height - panel_h + 17, "T", WHITE, 2);

    /* A native starter window. */
    uint32_t ww = fb->width > 900 ? 620 : fb->width * 2 / 3;
    uint32_t wh = fb->height > 650 ? 360 : fb->height * 2 / 5;
    uint32_t wx = (fb->width - ww) / 2;
    uint32_t wy = (fb->height - panel_h - wh) / 2;
    rect(wx + 6, wy + 8, ww, wh, 0x11151C);
    rect(wx, wy, ww, wh, WINDOW);
    rect(wx, wy, ww, 34, TITLE);
    rect(wx + ww - 28, wy + 8, 18, 18, 0xB94A48);
    text(wx + 14, wy + 10, "TESTOS", WHITE, 2);
    text(wx + 24, wy + 70, "WELCOME", TEXT, 3);
    text(wx + 24, wy + 112, "NATIVE DESKTOP", TEXT, 2);
    text(wx + 24, wy + 150, "GRAPHICS ONLINE", ACCENT, 2);

    /* Desktop icons represented by small application tiles. */
    rect(28, 38, 64, 64, ACCENT);
    text(43, 55, "T", WHITE, 4);
    text(28, 112, "TESTOS", WHITE, 1);

    /* Register the first window in the compositor registry. */
    if (compositor_window_count() == 0)
        compositor_create_window(wx, wy, ww, wh);
}

void desktop_init(void) {
    desktop_redraw();
}
