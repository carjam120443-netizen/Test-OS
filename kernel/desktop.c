/* A tiny native desktop: framebuffer drawing now, real window surfaces later. */
static const uint32_t BG = 0x202938;
static const uint32_t PANEL = 0x151A22;
static const uint32_t PANEL_EDGE = 0x364152;
static const uint32_t WINDOW = 0xE8ECF1;
static const uint32_t TITLE = 0x303A4A;
static const uint32_t TEXT = 0x20242B;
static const uint32_t ACCENT = 0x4F8CFF;
static const uint32_t WHITE = 0xFFFFFF;

static void rect(uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint32_t color) {
    const struct framebuffer *fb = graphics_framebuffer();
    if (!graphics_ready() || x >= fb->width || y >= fb->height) return;
    if (w > fb->width - x) w = fb->width - x;
    if (h > fb->height - y) h = fb->height - y;
    for (uint32_t yy = y; yy < y + h; ++yy)
        for (uint32_t xx = x; xx < x + w; ++xx)
            graphics_putpixel(xx, yy, color);
}

